print("Loop: for, while, break, continue, do while")

# ---------For Loop----------
print("For Loop")
for i in range(10):
    print("Loop: ", i)
print("-----------------------")

# ---------While Loop----------
print("While Loop")
i = 0
while i < 10:
    print("Loop: ", i)
    i += 1
print("While Loop Ended")
print("-----------------------")
